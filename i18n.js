/**
 * Texts of the user interface in German and English, the current language and the matching locale.
 * Pure module without DOM or storage access, usable in the browser and in Node.
 * @module i18n
 */

/** Supported languages. */
export const LANGUAGES = ['de', 'en'];

/** Language used when nothing (valid) is chosen. */
export const DEFAULT_LANGUAGE = 'de';

const LOCALES = { de: 'de-DE', en: 'en-US' };

let current = DEFAULT_LANGUAGE;

/**
 * Sets the current language; unknown values fall back to the default language.
 * @param {string} lang Language code.
 * @returns {string} Language now in use.
 */
export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;
  return current;
}

/**
 * Returns the current language.
 * @returns {string} Language code.
 */
export function language() {
  return current;
}

/**
 * Returns the locale for number and date formats of the current language.
 * @returns {string} Locale such as "de-DE".
 */
export function locale() {
  return LOCALES[current];
}

/**
 * Looks up a text of the current language, falling back to German and then to the key.
 * Function entries are called with the given, already formatted arguments.
 * @param {string} key Text key.
 * @param {...*} args Arguments for texts with placeholders.
 * @returns {*} Text, or the array/object stored under the key.
 */
export function t(key, ...args) {
  const entry = TEXTS[current][key] ?? TEXTS.de[key];
  return typeof entry === 'function' ? entry(...args) : entry ?? key;
}

